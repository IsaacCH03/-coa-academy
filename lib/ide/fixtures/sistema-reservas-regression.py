import ttkbootstrap as ttk
from ttkbootstrap.constants import *

class SistemaReservas:
    def __init__(self, root):
        self.root = root
        self.root.title("COA - Sistema de Reservas")
        self.root.geometry("1100x720")
        self.main = ttk.Frame(root, padding=14)
        self.main.pack(fill=BOTH, expand=YES)
        self.header = ttk.Frame(self.main)
        self.header.pack(fill=X, pady=8)
        self.titulo = ttk.Label(self.header, text="Sistema de Reservas", font=("Arial", 22, "bold"), bootstyle="primary")
        self.titulo.pack(side=LEFT)
        self.btn_nueva = ttk.Button(self.header, text="Nueva reserva", bootstyle="success", font=("Arial", 13))
        self.btn_nueva.pack(side=RIGHT, padx=8)
        self.activo = ttk.Checkbutton(self.header, text="Sistema activo", bootstyle="success")
        self.activo.pack(side=RIGHT, padx=8)
        self.separador = ttk.Separator(self.main)
        self.separador.pack(fill=X, pady=6)
        self.tabs = ttk.Notebook(self.main)
        self.tabs.pack(fill=BOTH, expand=YES)
        self.tab_reservas = ttk.Frame(self.tabs, padding=12)
        self.tab_config = ttk.Frame(self.tabs, padding=12)
        self.tabs.add(self.tab_reservas, text="Reservas")
        self.tabs.add(self.tab_config, text="Configuración")
        self.formulario = ttk.Labelframe(self.tab_reservas, text="Datos de la reserva", padding=12)
        self.formulario.pack(fill=X, pady=8)
        self.lbl_cliente = ttk.Label(self.formulario, text="Nombre del cliente")
        self.lbl_cliente.grid(row=0, column=0, padx=8, pady=8)
        self.entry_cliente = ttk.Entry(self.formulario, width=30)
        self.entry_cliente.grid(row=0, column=1, padx=8, pady=8, sticky=EW)
        self.lbl_habitacion = ttk.Label(self.formulario, text="Habitación")
        self.lbl_habitacion.grid(row=0, column=2, padx=8, pady=8)
        self.combo_habitacion = ttk.Combobox(self.formulario, values=["Individual", "Doble", "Suite"], width=18)
        self.combo_habitacion.grid(row=0, column=3, padx=8, pady=8)
        self.lbl_pago = ttk.Label(self.formulario, text="Método de pago")
        self.lbl_pago.grid(row=1, column=0, padx=8, pady=8)
        self.combo_pago = ttk.Combobox(self.formulario, values=["SINPE Móvil", "Tarjeta", "Efectivo"], width=18)
        self.combo_pago.grid(row=1, column=1, padx=8, pady=8)
        self.vip = ttk.Radiobutton(self.formulario, text="Reserva VIP", value="vip")
        self.vip.grid(row=1, column=2, padx=8, pady=8)
        self.acciones = ttk.Frame(self.tab_reservas)
        self.acciones.pack(fill=X, pady=8)
        self.guardar = ttk.Button(self.acciones, text="Guardar reserva", bootstyle="success")
        self.guardar.pack(side=LEFT, padx=5)
        self.editar = ttk.Button(self.acciones, text="Editar", bootstyle="warning")
        self.editar.pack(side=LEFT, padx=5)
        self.eliminar = ttk.Button(self.acciones, text="Eliminar", bootstyle="danger")
        self.eliminar.pack(side=LEFT, padx=5)
        self.tabla = ttk.Treeview(self.tab_reservas, columns=("cliente", "habitacion", "estado"), show="headings", height=8)
        self.tabla.heading("cliente", text="Cliente")
        self.tabla.heading("habitacion", text="Habitación")
        self.tabla.heading("estado", text="Estado")
        self.tabla.column("cliente", width=250)
        self.tabla.column("habitacion", width=160)
        self.tabla.column("estado", width=140)
        self.tabla.pack(fill=BOTH, expand=YES, pady=8)
        self.preferencias = ttk.Labelframe(self.tab_config, text="Preferencias", padding=12)
        self.preferencias.pack(fill=X, pady=8)
        self.escala = ttk.Scale(self.preferencias, orient=HORIZONTAL, length=260)
        self.escala.pack(fill=X, padx=10, pady=10)
        self.btn_config = ttk.Button(self.preferencias, text="Guardar configuración", bootstyle="primary")
        self.btn_config.pack(pady=8)

root = ttk.Window(themename="superhero")
app = SistemaReservas(root)
root.mainloop()
