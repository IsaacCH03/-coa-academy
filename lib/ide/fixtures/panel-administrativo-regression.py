import ttkbootstrap as ttk
from ttkbootstrap.constants import *

class PanelAdministrativo:
    def __init__(self, root):
        self.root = root
        self.root.title("COA - Panel Administrativo")
        self.root.geometry("1200x760")
        self.main = ttk.Frame(root, padding=16)
        self.main.pack(fill=BOTH, expand=YES)
        self.header = ttk.Frame(self.main)
        self.header.pack(fill=X, pady=8)
        self.titulo = ttk.Label(self.header, text="Panel Administrativo", font=("Arial", 22, "bold"), bootstyle="primary")
        self.titulo.pack(side=LEFT)
        self.perfil = ttk.Button(self.header, text="Mi perfil", bootstyle="secondary-outline")
        self.perfil.pack(side=RIGHT, padx=5)
        self.cerrar = ttk.Button(self.header, text="Cerrar sesión", bootstyle="danger-outline")
        self.cerrar.pack(side=RIGHT, padx=5)
        self.superior = ttk.Separator(self.main)
        self.superior.pack(fill=X, pady=5)
        self.cuerpo = ttk.Frame(self.main)
        self.cuerpo.pack(fill=BOTH, expand=YES)
        self.sidebar = ttk.Labelframe(self.cuerpo, text="Herramientas", padding=12)
        self.sidebar.pack(side=LEFT, fill=Y, padx=6)
        self.admin = ttk.Label(self.sidebar, text="Administrador", font=("Arial", 14, "bold"))
        self.admin.pack(pady=8)
        self.inicio = ttk.Button(self.sidebar, text="Inicio", bootstyle="primary")
        self.inicio.pack(fill=X, pady=4)
        self.estudiantes = ttk.Button(self.sidebar, text="Estudiantes")
        self.estudiantes.pack(fill=X, pady=4)
        self.reportes = ttk.Button(self.sidebar, text="Reportes")
        self.reportes.pack(fill=X, pady=4)
        self.sep_sidebar = ttk.Separator(self.sidebar)
        self.sep_sidebar.pack(fill=X, pady=12)
        self.nivel = ttk.Label(self.sidebar, text="Nivel de actividad")
        self.nivel.pack()
        self.escala_vertical = ttk.Scale(self.sidebar, orient=VERTICAL, length=150)
        self.escala_vertical.pack(pady=8)
        self.progreso_vertical = ttk.Progressbar(self.sidebar, orient=VERTICAL, length=140, value=72, maximum=100, bootstyle="success")
        self.progreso_vertical.pack(pady=8)
        self.porcentaje = ttk.Label(self.sidebar, text="72%")
        self.porcentaje.pack()
        self.contenido = ttk.Frame(self.cuerpo)
        self.contenido.pack(side=LEFT, fill=BOTH, expand=YES, padx=10)
        self.tarjetas = ttk.Frame(self.contenido)
        self.tarjetas.pack(fill=X, pady=8)
        self.pendientes = ttk.Labelframe(self.tarjetas, text="Pendientes", padding=12)
        self.pendientes.pack(side=LEFT, fill=X, expand=YES, padx=5)
        self.valor_pendientes = ttk.Label(self.pendientes, text="128", font=("Arial", 20, "bold"))
        self.valor_pendientes.pack()
        self.revisiones = ttk.Labelframe(self.tarjetas, text="Revisiones", padding=12)
        self.revisiones.pack(side=LEFT, fill=X, expand=YES, padx=5)
        self.valor_revisiones = ttk.Label(self.revisiones, text="36", font=("Arial", 20, "bold"))
        self.valor_revisiones.pack()
        self.actividad = ttk.Labelframe(self.contenido, text="Actividad reciente", padding=10)
        self.actividad.pack(fill=BOTH, expand=YES, pady=8)
        self.tabla = ttk.Treeview(self.actividad, columns=("nombre", "curso", "estado"), show="headings", height=7)
        self.tabla.heading("nombre", text="Nombre")
        self.tabla.heading("curso", text="Curso")
        self.tabla.heading("estado", text="Estado")
        self.tabla.column("nombre", width=240)
        self.tabla.column("curso", width=180)
        self.tabla.column("estado", width=120)
        self.tabla.pack(fill=BOTH, expand=YES)
        self.notas = ttk.Labelframe(self.contenido, text="Notas administrativas", padding=10)
        self.notas.pack(fill=X, pady=8)
        self.text_notas = ttk.Text(self.notas, width=60, height=4)
        self.text_notas.pack(fill=X)
        self.footer = ttk.Frame(self.main)
        self.footer.pack(fill=X, pady=8)
        self.salir = ttk.Button(self.footer, text="Salir", bootstyle="danger")
        self.salir.place(x=20, y=8, width=120, height=36)

root = ttk.Window(themename="darkly")
app = PanelAdministrativo(root)
root.mainloop()
