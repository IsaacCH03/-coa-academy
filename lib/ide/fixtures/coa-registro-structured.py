import ttkbootstrap as ttk
from ttkbootstrap.constants import *

root = ttk.Window(themename="superhero")
root.title("COA Registro")
root.geometry("1000x700")
main = ttk.Frame(root, padding=24)
main.pack(fill=BOTH, expand=YES)
titulo = ttk.Label(main, text="COA REGISTRO", font=("Arial", 24, "bold"), bootstyle="primary")
titulo.pack(fill=X, pady=10)
datos = ttk.Labelframe(main, text="Datos de estudiante", padding=12)
datos.pack(fill=X, pady=12)
lbl_nombre = ttk.Label(datos, text="Nombre Completo")
lbl_nombre.grid(row=0, column=0, padx=8, pady=12)
entry_nombre = ttk.Entry(datos, width=30)
entry_nombre.grid(row=0, column=1, sticky=EW, padx=8, pady=12)
lbl_curso = ttk.Label(datos, text="Curso")
lbl_curso.grid(row=0, column=2, padx=8, pady=12)
combo_curso = ttk.Combobox(datos, values=["Python", "Web", "SQL"], state="readonly", width=22)
combo_curso.grid(row=0, column=3, sticky=EW, padx=8, pady=12)
datos.columnconfigure(1, weight=1)
datos.columnconfigure(3, weight=1)
contenido = ttk.Frame(main)
contenido.pack(fill=BOTH, expand=YES, pady=12)
tabla = ttk.Treeview(contenido, columns=("nombre", "curso"), show="headings", height=10)
tabla.heading("nombre", text="Nombre")
tabla.heading("curso", text="Curso")
tabla.column("nombre", width=430, anchor="w", stretch=True)
tabla.column("curso", width=250, anchor="w", stretch=True)
tabla.pack(side=LEFT, fill=BOTH, expand=YES)
registrar = ttk.Button(contenido, text="Registrar", bootstyle="success")
registrar.pack(side=RIGHT, padx=12)

root.mainloop()
